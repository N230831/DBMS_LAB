SELECT CATEGORYID,COUNT(*) AS COUNTOFCAT FROM RECORDS GROUP BY CATEGORYID;
SELECT CATEGORYID,AVG(RATING) AS AVGCAT FROM RECORDS GROUP BY CATEGORYID;
SELECT MAX(PRICE),MIN(PRICE) FROM RECORDS;
SELECT * FROM RECORDS ORDER BY DOWNLOADS DESC;
SELECT DEVELOPERSID,COUNT(*) FROM RECORDS GROUP BY DEVELOPERSID;
SELECT CATEGORYID,COUNT(*) AS COU FROM RECORDS GROUP BY CATEGORYID HAVING COU>1;


-- PRACTICE
SELECT DEVELOPERSID,SUM(DOWNLOADS) AS TOTAL FROM RECORDS GROUP BY DEVELOPERSID;
SELECT PUBLISHERID,AVG(RATING) AS AVGRAT FROM RECORDS GROUP BY PUBLISHERID;
SELECT D.DEVELOPERSID,D.DEVELOPERNAME,COUNT(R.APPID) AS COUNTID FROM DEVELOPERS D JOIN RECORDS R  ON R.DEVELOPERSID=R.DEVELOPERSID GROUP BY D.DEVELOPERSID,D.DEVELOPERNAME HAVING COUNTID>1 ;
SELECT C.CATEGORYID,C.CATEGORYNAME,AVG(R.RATING) AS AVGRAT FROM CATEGORIES C JOIN RECORDS R GROUP BY C.CATEGORYID HAVING AVGRAT>4.3;
SELECT C.CATEGORYID,C.CATEGORYNAME ,COUNT(*) AS COUN FROM CATEGORIES C JOIN RECORDS R ON R.CATEGORYID=C.CATEGORYID  GROUP BY CATEGORYID ORDER BY COUN DESC;
